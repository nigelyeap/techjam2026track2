"""iter65: independent re-verification of Xuxia's per-segment blend-alpha
finding (see experiments/LEDGER.md). Replaces the single global alpha=0.14
with a per-segment alpha (by `tab`, 15 values; by decayed-activity tertile,
3 values), each segment's alpha chosen by sweeping on THAT segment's valid
rows only, then applied to the matching test rows. Compared against the
global-alpha blend, across all 5 GBM seeds already generated by
gen_scores.py.
"""
import os, sys
import numpy as np

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.join(_THIS_DIR, '..', '..')
sys.path.insert(0, _REPO_ROOT)
from evaluate import evaluate  # noqa: E402

ALPHA_GLOBAL = 0.14
GRID = np.round(np.arange(0.0, 0.41, 0.02), 2)


def minmax(x):
    x = np.asarray(x, dtype=np.float64); lo, hi = x.min(), x.max()
    return (x - lo) / (hi - lo + 1e-12)


def best_alpha_for_mask(fm, gbm_norm, u, y, mask, grid=GRID):
    if mask.sum() < 5:
        return ALPHA_GLOBAL  # too few rows to fit meaningfully; fall back to global
    best_a, best_v = ALPHA_GLOBAL, -1
    um, ym = u[mask], y[mask]
    for a in grid:
        s = a * fm[mask] + (1 - a) * gbm_norm[mask]
        v = evaluate(um, ym, s)['primary']
        if v > best_v:
            best_v, best_a = v, a
    return best_a


def segment_blend(fm_va, fm_te, gbm_va_norm, gbm_te_norm, u_va, y_va, u_te, y_te, seg_va, seg_te):
    out_va = np.empty_like(fm_va)
    out_te = np.empty_like(fm_te)
    for s in np.unique(seg_va):
        mva = (seg_va == s)
        a = best_alpha_for_mask(fm_va, gbm_va_norm, u_va, y_va, mva)
        out_va[mva] = a * fm_va[mva] + (1 - a) * gbm_va_norm[mva]
        mte = (seg_te == s)
        if mte.any():
            out_te[mte] = a * fm_te[mte] + (1 - a) * gbm_te_norm[mte]
    # any test segment value never seen in valid (shouldn't happen for tab/tertile) -> global alpha
    unseen_te = ~np.isin(seg_te, np.unique(seg_va))
    if unseen_te.any():
        out_te[unseen_te] = ALPHA_GLOBAL * fm_te[unseen_te] + (1 - ALPHA_GLOBAL) * gbm_te_norm[unseen_te]
    return out_va, out_te


if __name__ == '__main__':
    d = np.load(os.path.join(_THIS_DIR, 'scores_5seed.npz'), allow_pickle=True)
    y_va, y_te, u_va, u_te = d['y_va'], d['y_te'], d['u_va'], d['u_te']
    fm_va, fm_te = d['fm_va_ens'], d['fm_te_ens']
    tab_va, tab_te = d['tab_va'], d['tab_te']
    act_va, act_te = d['activity_va'], d['activity_te']

    # activity tertiles: cut points from VALID only (no test leakage)
    q1, q2 = np.quantile(act_va, [1/3, 2/3])
    tier_va = np.digitize(act_va, [q1, q2])
    tier_te = np.digitize(act_te, [q1, q2])

    print(f"tab segments in valid: {len(np.unique(tab_va))}; sizes(min/median/max)="
          f"{np.min(np.unique(tab_va, return_counts=True)[1])}/"
          f"{int(np.median(np.unique(tab_va, return_counts=True)[1]))}/"
          f"{np.max(np.unique(tab_va, return_counts=True)[1])}")
    print(f"tier sizes: {np.unique(tier_va, return_counts=True)[1]}")

    deltas_tab_va, deltas_tab_te, deltas_tier_va, deltas_tier_te = [], [], [], []
    for seed in range(5):
        gbm_va_norm = minmax(d['gbm_va_raw'][seed])
        gbm_te_norm = minmax(d['gbm_te_raw'][seed])
        global_va = ALPHA_GLOBAL * fm_va + (1 - ALPHA_GLOBAL) * gbm_va_norm
        global_te = ALPHA_GLOBAL * fm_te + (1 - ALPHA_GLOBAL) * gbm_te_norm
        gva_m = evaluate(u_va, y_va, global_va)['primary']
        gte_m = evaluate(u_te, y_te, global_te)['primary']

        tab_va_blend, tab_te_blend = segment_blend(fm_va, fm_te, gbm_va_norm, gbm_te_norm,
                                                     u_va, y_va, u_te, y_te, tab_va, tab_te)
        tva_m = evaluate(u_va, y_va, tab_va_blend)['primary']
        tte_m = evaluate(u_te, y_te, tab_te_blend)['primary']

        tier_va_blend, tier_te_blend = segment_blend(fm_va, fm_te, gbm_va_norm, gbm_te_norm,
                                                       u_va, y_va, u_te, y_te, tier_va, tier_te)
        tiva_m = evaluate(u_va, y_va, tier_va_blend)['primary']
        tite_m = evaluate(u_te, y_te, tier_te_blend)['primary']

        print(f"seed={seed}  global valid={gva_m:.5f} test={gte_m:.5f}  |  "
              f"by-tab valid={tva_m:.5f} ({tva_m-gva_m:+.5f}) test={tte_m:.5f} ({tte_m-gte_m:+.5f})  |  "
              f"by-tier valid={tiva_m:.5f} ({tiva_m-gva_m:+.5f}) test={tite_m:.5f} ({tite_m-gte_m:+.5f})",
              flush=True)
        deltas_tab_va.append(tva_m - gva_m); deltas_tab_te.append(tte_m - gte_m)
        deltas_tier_va.append(tiva_m - gva_m); deltas_tier_te.append(tite_m - gte_m)

    deltas_tab_va = np.array(deltas_tab_va); deltas_tier_va = np.array(deltas_tier_va)
    print(f"\nby-tab:  mean delta valid={deltas_tab_va.mean():+.5f}  wins={int((deltas_tab_va>0).sum())}/5  "
          f"mean delta test={np.mean(deltas_tab_te):+.5f}")
    print(f"by-tier: mean delta valid={deltas_tier_va.mean():+.5f}  wins={int((deltas_tier_va>0).sum())}/5  "
          f"mean delta test={np.mean(deltas_tier_te):+.5f}")
